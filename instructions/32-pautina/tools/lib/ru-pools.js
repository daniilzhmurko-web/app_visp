function femSurname(m) {
  if (/(ов|ев|ёв|ин|ын)$/.test(m)) return m + 'а';
  if (/ский$/.test(m)) return m.replace(/ский$/, 'ская');
  if (/цкий$/.test(m)) return m.replace(/цкий$/, 'цкая');
  if (/ой$/.test(m)) return m.replace(/ой$/, 'ая');
  if (/ий$/.test(m)) return m.replace(/ий$/, 'ая');
  return m;
}

